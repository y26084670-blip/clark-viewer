import { createHash, randomUUID } from "node:crypto";
import { readFile, writeFile, mkdir, rename, rm } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { rolldown } from "rolldown";

export async function buildProtocolScene() {
  const root = new URL("../", import.meta.url);
  const bundle = await rolldown({ input: fileURLToPath(new URL("src/services/protocol/protocolSceneEntry.js", root)),
    platform: "browser", treeshake: true });
  try {
    const result = await bundle.generate({ format: "iife", minify: true });
    if (result.output.length !== 1 || result.output[0].type !== "chunk" || result.output[0].imports.length || result.output[0].dynamicImports.length) {
      throw new Error("3D-протокол должен содержать единственный встроенный скрипт без внешних импортов.");
    }
    const code = result.output[0].code.replace(/<\/script/gi, "<\\/script");
    const hash = createHash("sha256").update(code).digest("base64");
    const license = await readFile(new URL("node_modules/three/LICENSE", root), "utf8");
    const content = `// Generated by scripts/build-protocol-scene.mjs; do not edit.\nexport const sceneRuntime = ${JSON.stringify(code)};\nexport const sceneRuntimeHash = ${JSON.stringify(hash)};\nexport const sceneRuntimeLicense = ${JSON.stringify(license)};\n`;
    const target = new URL("src/services/protocol/generated/sceneRuntime.js", root);
    await mkdir(new URL("./", target), { recursive: true });
    let previous;
    try { previous = await readFile(target, "utf8"); } catch { /* First build. */ }
    if (previous !== content) {
      const temporary = new URL(`sceneRuntime.${process.pid}.${randomUUID()}.tmp`, target);
      try { await writeFile(temporary, content); await rename(temporary, target); }
      finally { await rm(temporary, { force: true }); }
    }
  } finally { await bundle.close(); }
}
if (process.argv[1] === fileURLToPath(import.meta.url)) await buildProtocolScene();
