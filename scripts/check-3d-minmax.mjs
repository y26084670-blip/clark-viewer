import assert from 'node:assert/strict';
import {mkdtemp,readFile,writeFile,mkdir,rm,copyFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {createServer} from 'vite';
import solid from 'vite-plugin-solid';
import {parseGIF,decompressFrames} from 'gifuct-js';

const root=fileURLToPath(new URL('..',import.meta.url));
const out=process.env.CHECK_OUTPUT||path.join(root,'verification-output');
await mkdir(out,{recursive:true});
const dir=await mkdtemp(path.join(root,'__minmax_acceptance_'));
await copyFile(path.join(root,'scripts/test-support/3dMinmaxBrowserFixture.jsx'),path.join(dir,'fixture.jsx'));
await writeFile(path.join(dir,'index.html'),'<!doctype html><html><head><meta charset="UTF-8"></head><body><div id="root"></div><script type="module" src="./fixture.jsx"></script></body></html>');
const checks=[],errors=[];let server,browser,page;
const pass=name=>{checks.push(name);console.log(`PASS ${checks.length}: ${name}`);};
try{
 const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
 server=await createServer({configFile:false,root,plugins:[solid()],server:{host:'127.0.0.1',port:0,hmr:false},optimizeDeps:{include:['solid-js','solid-js/web','three','gifenc','tabulator-tables']}});
 await server.listen();
 browser=await chromium.launch({headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader']});
 page=await browser.newPage({viewport:{width:1920,height:1080},deviceScaleFactor:1});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/${path.basename(dir)}/index.html`);
 const waitTime=async t=>page.waitForFunction(t=>document.querySelector('.sources-fields-status')?.textContent.includes(`Показан шаг ${t}`),t);
 const legends=()=>page.evaluate(()=>Object.fromEntries(Array.from(document.querySelectorAll('.geometry-scalar-legend')).map(el=>[el.querySelector('strong')?.textContent,Array.from(el.querySelectorAll('.geometry-scalar-legend-limits span'),s=>Number(s.textContent))])));
 const waitRange=async(value)=>page.waitForFunction(value=>Array.from(document.querySelectorAll('.geometry-scalar-legend')).some(el=>el.querySelector('strong')?.textContent==='Элементы'&&Number(el.querySelector('.geometry-scalar-legend-limits span:last-child')?.textContent)===value),value);
 await waitTime(0);await waitRange(5);
 const global=page.getByRole('checkbox',{name:'Общий минмакс',exact:true});
 assert.equal(await global.isDisabled(),false);assert.equal(await global.isChecked(),false);
 assert.equal(await page.getByRole('combobox',{name:'Виртуальные',exact:true}).count(),1);
 assert.equal(await page.getByRole('checkbox',{name:'Карта',exact:true}).count(),1);
 assert.doesNotMatch(await page.locator('.sources-fields-toolbar').innerText(),/Виртуальные элементы|Цветовая карта/);
 pass('Short 3D labels and enabled, initially unchecked global range control');
 const before=await page.evaluate(()=>window.minmax.snapshot());
 await global.check();await waitRange(150);
 assert.deepEqual((await legends()).Области,[5,100]);
 const virtual=(await legends()).Виртуальные;
 assert.ok(Math.abs(virtual[0]-5*4*Math.PI*1e-7)<1e-10);
 assert.ok(Math.abs(virtual[1]-50*4*Math.PI*1e-7)<1e-9);
 assert.equal((await page.evaluate(()=>window.minmax.snapshot())).readCount,before.readCount);
 pass('All three groups use HDF5 global bounds with no field reread or second A/B conversion');
 const bounds=await legends();
 await page.evaluate(()=>window.minmax.setTime(2));await waitTime(2);await waitRange(150);
 assert.deepEqual(await legends(),bounds);
 pass('Global colour ranges stay fixed across time');
 await global.uncheck();await waitRange(15);
 pass('Disabling global mode restores the current-frame colour range');
 await global.check();await waitRange(150);
 await page.evaluate(()=>{window.minmax.setElements([]);window.minmax.setRegions([]);});await waitTime(2);await waitRange(150);
 assert.deepEqual(await legends(),bounds);
 pass('All elements/regions remain displayed after both list selections are cleared');
 await page.evaluate(()=>{window.minmax.setSetting('elementsMode','selected');window.minmax.setSetting('regionsMode','selected');});
 await page.waitForFunction(()=>document.querySelectorAll('.geometry-scalar-legend').length===0);
 assert.equal(await global.isDisabled(),true);
 pass('Selected-only with empty lists shows no results and disables global minmax');
 await page.evaluate(()=>{window.minmax.setElements([1]);window.minmax.setRegions([1]);});await waitTime(2);await waitRange(50);
 assert.deepEqual((await legends()).Области,[5,50]);
 pass('Selected-only reduces bounds to the original selected model IDs');
 await page.evaluate(()=>{window.minmax.setSetting('elementsMode','all');window.minmax.setSetting('regionsMode','all');});await waitTime(2);await waitRange(150);
 const toolbar=page.locator('.sources-fields-toolbar');const globalBox=await global.boundingBox();
 const paletteBox=await page.getByRole('combobox',{name:'Палитра',exact:true}).boundingBox();
 assert.ok(Math.abs(globalBox.y-paletteBox.y)<20);
 await page.screenshot({path:path.join(out,'3d-global-ranges.png'),fullPage:true});
 pass('Palette and global checkbox share the control row at desktop width');
 // Real Three/WebGL capture and the production GIF worker, including restoration.
 const dynamic=await page.evaluate(()=>window.minmax.movie());
 const decode=bytes=>{const data=Uint8Array.from(bytes);return decompressFrames(parseGIF(data.buffer),true);};
 assert.equal(dynamic.frames,3);assert.equal(decode(dynamic.bytes).length,3);
 await writeFile(path.join(out,'3d-global-dynamic.gif'),Uint8Array.from(dynamic.bytes));
 assert.equal((await page.evaluate(()=>window.minmax.snapshot())).time,2);assert.deepEqual(await legends(),bounds);
 pass('Real WebGL dynamic GIF contains three frames and restores time/global legends');
 await page.getByRole('combobox',{name:'Элементы',exact:true}).selectOption('JEdot');
 await waitTime(2);await waitRange(45);
 assert.match(await page.locator('.sources-fields-status').innerText(),/произведение модулей/);
 pass('Loss scale uses Jmin*Emin/Jmax*Emax, not exact signed dot extrema');
 await page.getByRole('combobox',{name:'Элементы',exact:true}).selectOption('MHdot');await waitTime(2);
 await page.waitForFunction(()=>Array.from(document.querySelectorAll('.geometry-scalar-legend')).some(el=>el.querySelector('strong')?.textContent==='Элементы'&&Number(el.querySelector('.geometry-scalar-legend-limits span:last-child')?.textContent)>20000));
 pass('Magnetic energy uses modulus products with the existing unit factor');
 await page.evaluate(()=>window.minmax.load('missing'));await waitTime(0);
 assert.equal(await global.isDisabled(),true);assert.equal(await global.isChecked(),false);
 assert.match(await page.locator('.sources-fields-status').innerText(),/Общий минмакс недоступен/);
 pass('Old HDF5 files stay viewable; unavailable global checkbox cannot be checked');
 await page.evaluate(()=>window.minmax.load('partial'));await waitTime(0);
 assert.equal(await global.isDisabled(),true);
 pass('Partial headers are not presented as full-cycle ranges');
 await page.getByRole('combobox',{name:'Элементы',exact:true}).selectOption('J');
 await page.evaluate(()=>window.minmax.load('complete',true));await waitTime(0);await waitRange(150);
 const staticGif=await page.evaluate(()=>window.minmax.movie());
 assert.equal(staticGif.frames,1);assert.equal(decode(staticGif.bytes).length,1);
 assert.equal(Buffer.from(staticGif.bytes).includes(Buffer.from('NETSCAPE2.0')),false);
 await writeFile(path.join(out,'3d-global-static.gif'),Uint8Array.from(staticGif.bytes));
 pass('A static zero-interval task exports a one-frame non-looping GIF with global bounds');
 await page.getByRole('checkbox',{name:'Карта',exact:true}).uncheck();
 await page.waitForFunction(()=>document.querySelectorAll('.geometry-scalar-legend').length===0);
 assert.equal(await global.isDisabled(),false);assert.equal(await global.isChecked(),true);
 await page.getByRole('checkbox',{name:'Карта',exact:true}).check();await waitRange(150);
 pass('Global mode remains available for vector arrows and survives representation changes');
 assert.deepEqual(errors,[]);
 await writeFile(path.join(out,'browser.json'),JSON.stringify({passed:checks.length,checks,errors},null,2));
 console.log(`BROWSER_OK ${checks.length}`);
}catch(error){
 if(page)await page.screenshot({path:path.join(out,'failure.png'),fullPage:true}).catch(()=>{});
 await writeFile(path.join(out,'browser.json'),JSON.stringify({passed:checks.length,checks,errors,failure:error.stack},null,2));
 console.error(error);process.exitCode=1;
}finally{await browser?.close();await server?.close();await rm(dir,{recursive:true,force:true});}
