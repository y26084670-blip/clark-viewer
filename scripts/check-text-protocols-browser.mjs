import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { createServer } from "vite";
import { TEXT_PROTOCOLS } from "../src/services/taskTextProtocols.js";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const root = fileURLToPath(new URL("../", import.meta.url));
const output = process.env.CHECK_OUTPUT || "/tmp/clark-text-protocols-check";
await mkdir(output, { recursive: true });
const server = await createServer({ root, cacheDir: `${output}/vite-cache`, server: { host: "127.0.0.1", port: 0, hmr: false } });
await server.listen();
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_EXECUTABLE, headless: true, args: ["--no-sandbox", "--disable-dev-shm-usage"] });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1200, height: 800 } });
  page.setDefaultTimeout(20000); page.on("pageerror", e => errors.push(e.message));
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/test/browser/textProtocols.html`);
  await page.waitForFunction(() => window.textProtocolsReady);
  const button = page.getByRole("button", { name: "Протоколы...", exact: true });
  assert.equal(await button.isDisabled(), true);
  await page.evaluate(() => textProtocolFixture.select("B"));
  const buttonBox = await button.boundingBox(), demoBox = await page.getByRole("tab", { name: /^GIF/ }).boundingBox();
  assert.ok(buttonBox.x + buttonBox.width <= demoBox.x);
  await button.click();
  const dialog = page.getByRole("dialog", { name: "Текстовые протоколы" });
  assert.equal(await dialog.locator("button").count(), 3);
  assert.equal(await dialog.locator(".task-text-protocols-name").textContent(), "B");
  await page.screenshot({ path: `${output}/dialog.png` });
  await dialog.getByRole("button", { name: "Отмена", exact: true }).click();
  assert.ok(await button.evaluate(element => element === document.activeElement));
  console.log("PASS selected task, position, three actions and Cancel");
  await button.click(); await dialog.getByRole("button", { name: "Создать", exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.task-text-protocols-dialog [role="status"]')?.textContent === "Создано протоколов: 5.");
  const names = TEXT_PROTOCOLS.map(p => p.name);
  const texts = await page.evaluate(async names => Object.fromEntries(await Promise.all(names.map(async n => [n, await textProtocolFixture.text("B", `output3XX/${n}`)]))), names);
  for (const [name, text] of Object.entries(texts)) await writeFile(`${output}/${name}`, text);
  for (const text of Object.values(texts)) assert.equal((text.match(/iDTK/g) || []).length, 2);
  const vtsp = texts["prot-field-vtsp.txt"].split("\n").find(l => /^\s+1\s+1/.test(l)).trim().split(/\s+/).map(Number);
  assert.deepEqual(vtsp.slice(10), [7, 3, 10, 90, .5, 5, .1]);
  assert.ok(await page.evaluate(() => textProtocolFixture.binariesUnchanged("B")));
  assert.ok(!(await page.evaluate(() => textProtocolFixture.list("A"))).some(n => names.includes(n)));
  console.log("PASS real worker: all five files, both steps, VTSP, selected B only, HDF5 preserved");
  await dialog.getByRole("button", { name: "Создать", exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.task-text-protocols-dialog [role="status"]')?.textContent === "Создано протоколов: 5.");
  assert.equal(await page.evaluate(() => textProtocolFixture.text("B", "output3XX/prot-source-J.txt")), texts["prot-source-J.txt"]);
  console.log("PASS repeat Create replaces rather than appends");
  await page.evaluate(() => textProtocolFixture.corrupt("B"));
  await dialog.getByRole("button", { name: "Создать", exact: true }).click();
  await dialog.getByRole("alert").waitFor();
  assert.equal(await page.evaluate(() => textProtocolFixture.text("B", "output3XX/prot-source-J.txt")), texts["prot-source-J.txt"]);
  await page.evaluate(() => textProtocolFixture.restore("B"));
  console.log("PASS damaged HDF5 preserves previous protocols");
  await dialog.getByRole("button", { name: "Удалить", exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.task-text-protocols-dialog [role="status"]')?.textContent === "Удалено протоколов: 5.");
  assert.ok(!(await page.evaluate(() => textProtocolFixture.list("B"))).some(n => names.includes(n)));
  for (const name of ["prot-force.txt", "prot-psi.txt", "prot-QKV.txt", "prot-iter.txt"]) assert.equal(await page.evaluate(n => textProtocolFixture.text("B", `output3XX/${n}`), name), `keep ${name}`);
  assert.ok(await page.evaluate(() => textProtocolFixture.binariesUnchanged("B")));
  assert.equal(await page.evaluate(() => textProtocolFixture.text("B", "DOCS/README.txt")), "Documentation");
  await dialog.getByRole("button", { name: "Удалить", exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.task-text-protocols-dialog [role="status"]')?.textContent === "Текстовые протоколы отсутствуют.");
  await page.keyboard.press("Escape");
  assert.equal(await dialog.count(), 0);
  assert.deepEqual(errors, []);
  console.log("PASS batch Delete, absent files, preserved integrals/DOCS, Escape; no page errors");
} finally { await browser.close(); await server.close(); }
